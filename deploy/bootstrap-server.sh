#!/usr/bin/env bash
# deploy/bootstrap-server.sh - one-time preparation of an environment directory
# ON THE SERVER. Creates the directory, writes a .env with random secrets and the
# right ports, and optionally installs the GitHub Actions deploy key.
#
#   curl -fsSL https://raw.githubusercontent.com/OSSC-DBIT/DBIT-PageCraft/master/deploy/bootstrap-server.sh \
#     | bash -s -- staging    /srv/server-data/staging    "ssh-ed25519 AAAA... github-actions"
#   curl -fsSL https://raw.githubusercontent.com/OSSC-DBIT/DBIT-PageCraft/master/deploy/bootstrap-server.sh \
#     | bash -s -- production /srv/server-data/production "ssh-ed25519 AAAA... github-actions"
#
# Arguments:  <staging|production> [directory] [deploy public key]
# Existing .env files are never overwritten. The compose and nginx files are
# synced by the Deploy workflow on every run, so nothing else is needed here.
set -euo pipefail

ENV_NAME="${1:-}"
DIR="${2:-/srv/server-data/${ENV_NAME}}"
PUBKEY="${3:-}"

case "$ENV_NAME" in
  staging)    HTTP_PORT=8091; APP_PORT=3091; PROJECT=pagecraft-staging ;;
  production) HTTP_PORT=8090; APP_PORT=3090; PROJECT=pagecraft-prod ;;
  *) echo "usage: $0 <staging|production> [directory] [deploy public key]" >&2; exit 1 ;;
esac

log() { printf '[bootstrap] %s\n' "$*"; }
rand() { openssl rand -base64 "$1" | tr -d '=+/\n' | cut -c1-"$1"; }

command -v docker >/dev/null || { log "ERROR: docker is not installed"; exit 1; }
docker compose version >/dev/null 2>&1 || { log "ERROR: docker compose plugin is missing"; exit 1; }
if ! id -nG "$USER" | grep -qw docker; then
  log "WARNING: $USER is not in the docker group. Run: sudo usermod -aG docker $USER  (then log in again)"
fi

if [ ! -d "$DIR" ]; then
  log "creating $DIR"
  if mkdir -p "$DIR" 2>/dev/null; then :; else
    sudo mkdir -p "$DIR" && sudo chown "$USER":"$USER" "$DIR"
  fi
fi
mkdir -p "$DIR/nginx/conf.d" "$DIR/nginx/certs" "$DIR/deploy"

if [ -f "$DIR/.env" ]; then
  log ".env already exists in $DIR, leaving it untouched"
else
  ADMIN_PASSWORD="$(rand 24)"
  umask 077
  cat > "$DIR/.env" <<EOF
# Generated by deploy/bootstrap-server.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) for ${ENV_NAME}
COMPOSE_PROJECT_NAME=${PROJECT}
APP_ENV=${ENV_NAME}
# Empty: the host-level cloudflared publishes http://localhost:${HTTP_PORT}.
# Set to "tunnel" (and fill CF_TUNNEL_TOKEN) to run a cloudflared container instead.
COMPOSE_PROFILES=
CF_TUNNEL_TOKEN=

POSTGRES_DB=pagecraft
POSTGRES_USER=pagecraft
POSTGRES_PASSWORD=$(rand 40)

ADMIN_EMAIL=admin@dbit.local
ADMIN_PASSWORD=${ADMIN_PASSWORD}

SESSION_SECRET=$(rand 64)
SESSION_HOURS=8

HTTP_BIND=127.0.0.1
HTTP_PORT=${HTTP_PORT}
APP_PORT=${APP_PORT}
HTTPS_PORT=443

TRUST_PROXY=1
COOKIE_SECURE=true

# Managed by deploy/deploy.sh on every deploy:
APP_IMAGE=ghcr.io/ossc-dbit/dbit-pagecraft:${ENV_NAME}
APP_VERSION=
EOF
  log "wrote $DIR/.env (nginx 127.0.0.1:${HTTP_PORT}, app 127.0.0.1:${APP_PORT})"
  log "admin login: admin@dbit.local / ${ADMIN_PASSWORD}   <- store this, change ADMIN_EMAIL in .env if needed"
fi

if [ -n "$PUBKEY" ]; then
  mkdir -p ~/.ssh && chmod 700 ~/.ssh
  touch ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys
  if grep -qF "$PUBKEY" ~/.ssh/authorized_keys; then
    log "deploy key already in authorized_keys"
  else
    printf '%s\n' "$PUBKEY" >> ~/.ssh/authorized_keys
    log "deploy key added to ~/.ssh/authorized_keys"
  fi
fi

if ss -tln 2>/dev/null | grep -qE "[:.]${HTTP_PORT} " ; then
  log "WARNING: port ${HTTP_PORT} is already in use on this host; pick another HTTP_PORT in $DIR/.env"
fi
if ss -tln 2>/dev/null | grep -qE "[:.]${APP_PORT} " ; then
  log "WARNING: port ${APP_PORT} is already in use on this host; pick another APP_PORT in $DIR/.env"
fi

log "done. Next: run the Deploy workflow for '${ENV_NAME}' from GitHub Actions."
